function readStoredPreference(key, fallback) {
  try {
    return localStorage.getItem(key) || fallback;
  } catch {
    return fallback;
  }
}

function writeStoredPreference(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // The interface still works when storage is blocked by privacy settings.
  }
}

// Global variables for current state
let currentLang = readStoredPreference('site_lang', 'en');
let currentTheme = readStoredPreference('site_theme', 'light');

function t(key, placeholders = {}) {
  let text = (i18nDict[currentLang] && i18nDict[currentLang][key]) || key;
  for (const [k, v] of Object.entries(placeholders)) {
    text = text.replace(`{${k}}`, v);
  }
  return text;
}

function applyLanguage(lang) {
  currentLang = lang;
  writeStoredPreference('site_lang', lang);
  
  // Set direction
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  // Apply translations
  const dict = i18nDict[lang];
  if (!dict) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-label');
    if (dict[key]) {
      el.label = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) {
      el.title = dict[key];
    }
  });

  document.dispatchEvent(new CustomEvent('app:languagechange', { detail: { lang } }));
}

function applyTheme(theme) {
  currentTheme = theme;
  writeStoredPreference('site_theme', theme);
  
  if (theme === 'dark') {
    document.documentElement.setAttribute('data-theme', 'dark');
    document.getElementById('themeToggleBtn').innerHTML = '<i class="fa-solid fa-sun"></i>';
  } else {
    document.documentElement.removeAttribute('data-theme');
    document.getElementById('themeToggleBtn').innerHTML = '<i class="fa-solid fa-moon"></i>';
  }
}

// Initialize on script load
document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);
  applyTheme(currentTheme);

  // Bind Navbar toggle buttons
  const themeBtn = document.getElementById('themeToggleBtn');
  if (themeBtn) {
    themeBtn.addEventListener('click', () => {
      const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
      applyTheme(newTheme);
    });
  }

  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) {
    langBtn.addEventListener('click', () => {
      const newLang = currentLang === 'ar' ? 'en' : 'ar';
      applyLanguage(newLang);
    });
  }
});
